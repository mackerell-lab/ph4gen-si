# 'Donor', 'Acceptor', 'PosIonizable', 'NegIonizable', 'Aromatic', 'Hydrophobe', 'LumpedHydrophobe'
def rdkit_type(x):
  simple = []
  # determined that we want Aro|Hyd to simply have ['Aro', 'Hyd']
  ##if   ('Aro' in x) and ('Hyd' in x):       simple.append('LumpedHydrophobe') 
  if ('Aro' in x):                        simple.append('Aromatic')
  if ('Hyd' in x):                        simple.append('Hydrophobe')
  if ('Don' in x) and ('$hDon' not in x): simple.append('Donor')
  if ('Acc' in x) and ('$hAcc' not in x): simple.append('Acceptor')
  if ('Cat' in x) and ('$hCat' not in x): simple.append('PosIonizable') # Priority to Don over Cat
  if ('Ani' in x) and ('$hAni' not in x): simple.append('NegIonizable') # Priority to Acc over Ani
  return simple

features_df['rdkit_family'] = features_df['type'].apply(rdkit_type)
feat_coords = features_df[['x','y','z']].to_numpy()
feat_r = features_df['radius'].to_numpy() + args.pad
feat_fam = features_df['rdkit_family'].copy()

mols = Chem.SDMolSupplier(args.sdf, removeHs=False)

mol_to_features = {}

fdef = os.path.join(RDConfig.RDDataDir, "BaseFeatures.fdef")
feat_factory = ChemicalFeatures.BuildFeatureFactory(fdef)

for mol_i, mol in enumerate(mols):
  feats = feat_factory.GetFeaturesForMol(mol)
  # build family list for each atom
  atom_fam = [[] for _ in range(mol.GetNumAtoms())]

  for f in feats:
    fam = f.GetFamily()
    for aidx in f.GetAtomIds():
      atom_fam[aidx].append(fam)

  conf = mol.GetConformer() # need to initialize conf
  atom_coords = np.array([[conf.GetAtomPosition(a.GetIdx()).x,
                           conf.GetAtomPosition(a.GetIdx()).y,
                           conf.GetAtomPosition(a.GetIdx()).z]
                          for a in mol.GetAtoms()])

  # distance matrix: atoms x features
  dists = np.linalg.norm(atom_coords[:,None,:]-feat_coords[None,:,:], axis=2)
  hits = []
  # loop only over atoms (features stay vectorized)
  for i, atom_types in enumerate(atom_fam):
    if len(atom_types) == 0: # skip atoms with no features
      continue

    # find ANY matches between feature "family(s)" of atoms and silcs ph4 features
    # NOTE: this means that 'Donor' will match ['Donor','PosIonizable']
    type_match = np.array([any(t in ff for t in atom_types) for ff in feat_fam])
    # within that feature's radius
    radius_match = dists[i] <= feat_r
    good = np.where(type_match & radius_match)[0]
    hits.extend(good)

  #mol_to_features[mol_i] = np.array(hits)
  mol_to_features[mol_i] = set(hits)

