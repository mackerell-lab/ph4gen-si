def parse_ph4(filename, features_dat=None):
  feature_rows = []

  n_features = None
  reading_features = False
  features_read = 0

  with open(filename, 'r') as f:
    for line in f:
      stripped = line.strip()

      # all the initial lines before #feature is read are part of the header
      if stripped.startswith("#feature"):
        parts = stripped.split()
        n_features = int(parts[1])
        reading_features = True
        continue

      if reading_features and features_read < n_features:
        if not stripped or stripped.startswith("#"): continue

        parts = stripped.split()
        # based on example format
        feature_rows.append({
          "type": parts[0],
          "color": parts[1],
          "x": float(parts[2]),
          "y": float(parts[3]),
          "z": float(parts[4]),
          "radius": float(parts[5]),
          "ebits": int(parts[6]),
          "gbits": int(parts[7]),
        })
        features_read += 1

      if reading_features and features_read == n_features: break

  features_df = pd.DataFrame(feature_rows)

  if features_dat:
    # Read in <prot>.features.dat file with the FGFE for each feature
    # Type | Sphere Center X | Y | Z | Sphere radius R | FGFE

    feat_dat = pd.read_csv(features_dat, sep='\\s+', skiprows=2, names=['Type','X','Y','Z','Radius','FGFE'])
    if feat_dat.shape[0] == features_df.shape[0]:
      features_df['FGFE'] = feat_dat['FGFE'].copy()
    else:
      print(f'Although {features_dat} was supplied, the number of features do not match {filename}')
 
  return features_df

def write_ph4(filename, features_df):
  n_features = str(features_df.shape[0])
  header = [
  "#moe:ph4que 2011.1\n",
  "#SILCS pharmacophore hypothesis generated by ph4gen utility\n",
  "#pharmacophore 5 tag t value *\n",
  f"scheme t Unified matchsize i  {n_features} title t $ comment s $ smask i 476156\n",
  f"#feature {n_features} expr tt color ix x r y r z r r r ebits ix gbits ix\n"
  ]

  with open(filename, "w") as f:
    # write header as-is
    for line in header:
      f.write(line)
    # write features
    for _, row in features_df.iterrows():
      f.write(
        f"{row['type']:12s} "
        f"{row['color']:6s} "
        f"{row['x']:10.4f} "
        f"{row['y']:10.4f} "
        f"{row['z']:10.4f} "
        f"{row['radius']:6.3f} "
        f"{int(row['ebits'])} "
        f"{int(row['gbits'])}\n"
      )
    f.write("#endpharmacophore\n")

